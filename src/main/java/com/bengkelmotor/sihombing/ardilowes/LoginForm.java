    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = txtUsername.getText().trim();
String password = txtPassword.getText().trim();

if (username.isEmpty() || password.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Username dan password wajib diisi!"
    );
    return;
}

String url = "jdbc:mysql://localhost:3306/fernanda";

try {
    java.sql.Connection conn = 
        java.sql.DriverManager.getConnection(url, "root", "");

    java.sql.PreparedStatement ps = conn.prepareStatement(
        "SELECT * FROM pengguna WHERE username = ? AND password = ?"
    );

    ps.setString(1, username);
    ps.setString(2, password);

    try (java.sql.ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Login Berhasil! Selamat datang, " + username
            );
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Username atau password salah!"
            );
        }
    }
} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error Database: " + e.getMessage());
}

    }//GEN-LAST:event_jButton1ActionPerformed

